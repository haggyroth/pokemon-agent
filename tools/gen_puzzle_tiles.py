#!/usr/bin/env python3
"""Generate knowledge/puzzle_tiles.py from a pret/pokefirered checkout.

Usage: python tools/gen_puzzle_tiles.py [path-to-pokefirered] > knowledge/puzzle_tiles.py

PUZZLE_TILES maps (map_bank, map_id) -> [(x, y, kind)] for the interactive tiles that change a map's
walkable layout:
  "cardkey" — Silph Co. card-key door tiles (a `sign` bg_event whose script is ..._EventScript_Door*;
               face the door + A: it opens if you hold the Card Key)
  "switch"  — Pokémon Mansion secret-switch statues (..._EventScript_Statue; A -> "press it?" -> YES
               flips every barrier door on the whole mansion)
"""
import json
import os
import sys


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    out = {}
    for gi, gname in enumerate(groups["group_order"]):
        if not gname.startswith("gMapGroup_"):
            continue
        for ni, dname in enumerate(groups[gname]):
            mj = f"{pf}/data/maps/{dname}/map.json"
            if not os.path.exists(mj):
                continue
            d = json.load(open(mj))
            tiles = []
            for b in d.get("bg_events") or []:
                if b.get("type") != "sign":
                    continue
                sc = b.get("script", "")
                if dname.startswith("SilphCo_") and "_EventScript_Door" in sc:
                    tiles.append((int(b["x"]), int(b["y"]), "cardkey"))
                elif dname.startswith("PokemonMansion_") and sc.endswith("_EventScript_Statue"):
                    tiles.append((int(b["x"]), int(b["y"]), "switch"))
            if tiles:
                out[(gi, ni)] = sorted(tiles)
    w = sys.stdout.write
    w('"""Interactive puzzle tiles (card-key doors, mansion switches). GENERATED by\n')
    w('tools/gen_puzzle_tiles.py — do not edit."""\n\n')
    w("PUZZLE_TILES: dict[tuple[int, int], list[tuple[int, int, str]]] = {\n")
    for k in sorted(out):
        w(f"    {k}: {out[k]},\n")
    w("}\n")


if __name__ == "__main__":
    main()
