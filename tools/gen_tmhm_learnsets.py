#!/usr/bin/env python3
"""Generate knowledge/tmhm_learnsets.py from a pret/pokefirered checkout.

Usage: python tools/gen_tmhm_learnsets.py [path-to-pokefirered] > knowledge/tmhm_learnsets.py

LEARNSETS maps a species id (game internal id, same as the party struct) to a bitmask where bit k
means "can learn the k-th machine" (bit 0 = TM01 ... bit 49 = TM50, bit 50 = HM01 ... bit 57 = HM08).
"""
import os
import re
import sys


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    sp = {}
    for m in re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read()):
        sp[m.group(1)] = int(m.group(2))
    items = {}
    for m in re.finditer(r"#define ITEM_((?:TM|HM)\d\d)(?:_\w+)?\s+(\d+|ITEM_\w+)", open(f"{pf}/include/constants/items.h").read()):
        pass
    base = 289   # ITEM_TM01
    txt = open(f"{pf}/src/data/pokemon/tmhm_learnsets.h").read()
    out = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\]\s*=\s*TMHM_LEARNSET\((.*?)\),?\n\n", txt + "\n\n", re.S):
        name, body = m.group(1), m.group(2)
        if name not in sp or sp[name] == 0:
            continue
        mask = 0
        for t in re.finditer(r"TMHM\(((?:TM|HM)(\d\d))", body):
            n = int(t.group(2))
            mask |= 1 << ((n - 1) if t.group(1).startswith("TM") else (49 + n))
        out[sp[name]] = mask
    w = sys.stdout.write
    w('"""TM/HM compatibility per species. GENERATED by tools/gen_tmhm_learnsets.py — do not edit.\n\n')
    w("species id -> bitmask (bit k = machine k: 0..49 = TM01..TM50, 50..57 = HM01..HM08).\"\"\"\n\n")
    w("LEARNSETS: dict[int, int] = {\n")
    for k in sorted(out):
        w(f"    {k}: {out[k]:#x},\n")
    w("}\n\n\n")
    w("def can_learn(species_id: int, item_id: int) -> bool:\n")
    w("    \"\"\"True if the species can learn TM/HM `item_id` (289..346). Unknown species -> True (let the\n")
    w("    game decide rather than refuse wrongly).\"\"\"\n")
    w("    mask = LEARNSETS.get(species_id)\n")
    w("    return True if mask is None else bool(mask >> (item_id - 289) & 1)\n")


if __name__ == "__main__":
    main()
