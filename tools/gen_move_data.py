#!/usr/bin/env python3
"""Generate knowledge/move_data.py from a pret/pokefirered checkout.

Usage: python tools/gen_move_data.py [path-to-pokefirered] > knowledge/move_data.py

MOVE_DATA maps the move name (exactly as game.constants.MOVE_NAMES / the memory reader yields it)
to (base power, type code, max PP) for ALL Gen III moves. leafgreen_data merges it under its
hand-tuned tables so a damaging move is never mistaken for a status move just because the
curated list missed it (Thunder Shock, Horn Attack, Take Down, ...).
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from game.constants import MOVE_NAMES   # noqa: E402

TYPES = {"NORMAL": "NOR", "FIGHTING": "FIG", "FLYING": "FLY", "POISON": "POI", "GROUND": "GRD",
         "ROCK": "ROC", "BUG": "BUG", "GHOST": "GHO", "STEEL": "STL", "MYSTERY": "NOR",
         "FIRE": "FIR", "WATER": "WAT", "GRASS": "GRS", "ELECTRIC": "ELE", "PSYCHIC": "PSY",
         "ICE": "ICE", "DRAGON": "DRG", "DARK": "DRK"}


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in
           re.finditer(r"#define MOVE_(\w+)\s+(\d+)", open(f"{pf}/include/constants/moves.h").read())}
    txt = open(f"{pf}/src/data/battle_moves.h").read()
    out = {}
    for m in re.finditer(r"\[MOVE_(\w+)\]\s*=\s*\{(.*?)\n    \}", txt, re.S):
        name, body = m.group(1), m.group(2)
        mid = ids.get(name)
        if not mid or mid not in MOVE_NAMES:
            continue
        power = int(re.search(r"\.power = (\d+)", body).group(1))
        typ = TYPES[re.search(r"\.type = TYPE_(\w+)", body).group(1)]
        pp = int(re.search(r"\.pp = (\d+)", body).group(1))
        out[MOVE_NAMES[mid]] = (power, typ, pp)
    print('"""GENERATED by tools/gen_move_data.py from the pokefirered decomp — do not edit.\n'
          'move name -> (base power, type code, max PP)."""\n')
    print("MOVE_DATA: dict[str, tuple[int, str, int]] = {")
    for k in sorted(out):
        print(f"    {k!r}: {out[k]!r},")
    print("}")


if __name__ == "__main__":
    main()
