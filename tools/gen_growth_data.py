#!/usr/bin/env python3
"""Generate knowledge/growth_data.py (species id -> growth-rate index) from a pret/pokefirered checkout.

Usage: python tools/gen_growth_data.py [path-to-pokefirered] > knowledge/growth_data.py
The experience formulas themselves are closed-form and live in knowledge/growth.py.
"""
import os
import re
import sys

IDX = {"MEDIUM_FAST": 0, "ERRATIC": 1, "FLUCTUATING": 2, "MEDIUM_SLOW": 3, "FAST": 4, "SLOW": 5}


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in
           re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    txt = open(f"{pf}/src/data/pokemon/species_info.h").read()
    out = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\] =\n    \{(.*?)\n    \}", txt, re.S):
        name, body = m.group(1), m.group(2)
        g = re.search(r"\.growthRate = GROWTH_(\w+)", body)
        if name in ids and ids[name] and g:
            out[ids[name]] = IDX[g.group(1)]
    print('"""GENERATED by tools/gen_growth_data.py from the pokefirered decomp — do not edit.\n'
          'internal species id -> growth rate (0 medium-fast, 1 erratic, 2 fluctuating, 3 medium-slow, 4 fast, 5 slow)."""\n')
    print("GROWTH_RATE: dict[int, int] = {")
    for sid in sorted(out):
        print(f"    {sid}: {out[sid]},")
    print("}")


if __name__ == "__main__":
    main()
