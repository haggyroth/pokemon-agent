#!/usr/bin/env python3
"""Generate knowledge/species_data.py from a pret/pokefirered checkout.

Usage: python tools/gen_species_data.py [path-to-pokefirered] > knowledge/species_data.py

SPECIES_DATA maps the game's internal species id (same as the party struct) to
(base stat total, type codes, best BST anywhere in its evolution line). Used by the catch policy.
"""
import os
import re
import sys

TYPES = {"NORMAL": "NOR", "FIGHTING": "FIG", "FLYING": "FLY", "POISON": "POI", "GROUND": "GRD",
         "ROCK": "ROC", "BUG": "BUG", "GHOST": "GHO", "STEEL": "STL", "MYSTERY": "NOR",
         "FIRE": "FIR", "WATER": "WAT", "GRASS": "GRS", "ELECTRIC": "ELE", "PSYCHIC": "PSY",
         "ICE": "ICE", "DRAGON": "DRG", "DARK": "DRK"}


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in
           re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    txt = open(f"{pf}/src/data/pokemon/species_info.h").read()
    base = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\] =\n    \{(.*?)\n    \}", txt, re.S):
        name, body = m.group(1), m.group(2)
        if name not in ids or ids[name] == 0:
            continue
        stats = [int(re.search(rf"\.{k} = (\d+)", body).group(1))
                 for k in ("baseHP", "baseAttack", "baseDefense", "baseSpeed", "baseSpAttack", "baseSpDefense")]
        t = re.search(r"\.types = \{TYPE_(\w+), TYPE_(\w+)\}", body)
        types = tuple(dict.fromkeys(TYPES[x] for x in t.groups()))
        base[name] = (sum(stats), types)
    evo = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\]\s*=\s*\{(.*?)\},?\n", open(f"{pf}/src/data/pokemon/evolution.h").read()):
        evo[m.group(1)] = re.findall(r"SPECIES_(\w+)\}", m.group(2))

    def best(name, seen=()):
        b = base.get(name, (0, ()))[0]
        for nxt in evo.get(name, []):
            if nxt not in seen:
                b = max(b, best(nxt, seen + (name,)))
        return b

    print('"""GENERATED by tools/gen_species_data.py from the pokefirered decomp — do not edit.\n'
          'internal species id -> (base stat total, type codes, best BST in its evolution line)."""\n')
    print("SPECIES_DATA: dict[int, tuple[int, tuple[str, ...], int]] = {")
    for name in sorted(base, key=lambda n: ids[n]):
        print(f"    {ids[name]}: ({base[name][0]}, {base[name][1]!r}, {best(name)}),  # {name}")
    print("}")


if __name__ == "__main__":
    main()
