def region_at(mp: tuple[int, int], x: int, y: int) -> str:
    """Region tag of tile (x, y) on a cave map (a warp tile borrows a walkable neighbour)."""
    rows = CAVE_GRIDS[mp]
    h, w = len(rows), len(rows[0])
    for nx, ny in ((x, y), (x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
        if 0 <= nx < w and 0 <= ny < h and rows[ny][nx] != "#":
            return rows[ny][nx]
    return "0"
